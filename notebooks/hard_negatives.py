# -*- coding: utf-8 -*-
"""难负样本构造器:在真实答案上**受控注入**法律事实错误。

⚠️ 【先把名字说清楚】本模块**不是蒸馏**。
   蒸馏是强模型**生成文本**;这里是强模型**写规则**、规则**替换文本**。
   两者的差别是实质的:替换只能造出表里预设的那几十种错误,错误形态是封闭的。
   真正的蒸馏见不到 —— 项目里对应的位置是 `experiments/reject_sampling.py`
   (让模型自己生成 rejected),那才是 on-policy 的。

【它解决的问题】
02 原有的 6 个规则劣化函数造的 rejected **全部带有表面可见的特征**:

    corrupt_truncate     长度骤减一半
    corrupt_hallucinate  出现"第9999条"这种不存在的条号
    corrupt_vague        全文只剩 30 字
    corrupt_flip         凭空出现"不可以/不应当"
    corrupt_offtopic     整段被换掉
    corrupt_repeat       同一句重复 5~8 遍

模型只要学会 6 条浅层判别规则就能全部分对 —— 实测 04 的 rewards/accuracies
**起步就 0.875**(正常应在 0.5 附近)、整轮只爬到 0.94。

【本模块造的是什么】
四类**只在内容层面出错、表面完全看不出**的负样本。共同约束:
    · 不改长度(字数差 < 2%)
    · 不改结构(分点、语气、句式全部保留)
    · 引用的法条**真实存在**、条号格式合法
    · 错的只有几个字,而且每个字单独看都是正规法言法语

    corrupt_cite_shift   条号错位:换成同一部法真实存在但内容无关的条号
    corrupt_term_swap    术语误用:换成"看着像但法律效果完全不同"的近义术语
    corrupt_degree       程度偏移:量刑档次 / 期限 / 比例改档
    corrupt_subject      主体错置:权利义务主体对调

【它的价值和它的天花板】
价值:三张陷阱表是**领域知识的注入** —— "撤销"和"解除"字面都是两个字、
都表示合同终止,但撤销溯及既往、解除向将来,法律效果相反。知道哪些词对构成
这种陷阱,规则代码自己推不出来。而且错误是**受控注入**的,改了哪里、为什么错,
可以逐条核对(cite_shift 甚至能用 legal_check 自动验证)。

天花板:**它仍然是 off-policy 的**。DPO 压低的是 rejected 的对数概率,而
"把真实答案改几个字"得到的句子,本来就不在模型的高概率输出区域里,压它的收益
远小于压模型真正会写出来的错句。所以本模块的定位是**补充覆盖面**
(600 题全覆盖、零成本、可复现),主力应该是 reject_sampling.py 的 on-policy 负样本。
"""
