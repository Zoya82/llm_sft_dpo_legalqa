_CN = "一二三四五六七八九十百千零〇两"


def _sane(text, src):
    """质量闸门:造出来的负样本必须仍然像一篇正常的法律回答。"""
    if not text or text.strip() == src.strip():
        return False
    if abs(len(text) - len(src)) / max(1, len(src)) > 0.05:    # 长度不该有明显变化
        return False
    return not any(t in text for t in ILLEGAL_TOKENS)


