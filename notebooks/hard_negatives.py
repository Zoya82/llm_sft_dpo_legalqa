_D = "零一二三四五六七八九"

def _int2cn(n):
    """1234 -> 一千二百三十四;符合法条条号的中文写法(十位为 1 且无百位时省略'一')"""
    if n <= 0:
        return "零"
    if n < 10:
        return _D[n]
    if n < 20:
        return "十" + (_D[n % 10] if n % 10 else "")
    s, units, parts = str(n), ["", "十", "百", "千"], []
    L_ = len(s)
    for i, ch in enumerate(s):
        d = int(ch)
        u = units[L_ - i - 1]
        if d == 0:
            if parts and not parts[-1].endswith("零"):
                parts.append("零")
        else:
            parts.append(_D[d] + u)
    return "".join(parts).rstrip("零")


# =========================================================================
# 表面可分辨性:量化"这个 rejected 有多容易被一眼看穿"
# =========================================================================
def surface_gap(chosen, rejected):
    """返回 (长度变化率, 字符差异率)。两个数都接近 0 = 表面上几乎分辨不出。

    字符差异率用字符多重集的对称差 / 总量近似,比编辑距离便宜得多,
    在"局部小改"这个场景下足够区分数量级。
    """
    lc, lr = len(chosen), len(rejected)
    len_gap = abs(lr - lc) / max(1, lc)
    ca, cb = Counter(chosen), Counter(rejected)
    diff = sum((ca - cb).values()) + sum((cb - ca).values())
    return len_gap, diff / max(1, lc + lr)
