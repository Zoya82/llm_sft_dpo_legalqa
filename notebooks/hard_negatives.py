def corrupt_cite_shift(ans, law_db, rng=random, max_shift=12):
    """条号错位:把引用的条号换成**同一部法律里真实存在、但内容无关**的条号。

    这是四类里唯一能被 legal_check 自动验证的 —— 替换后核验器应判 misattributed。

    和 corrupt_hallucinate 的差别是全部要害:
        hallucinate  《民法典》第9999条  → 条号不存在,一眼假
        cite_shift   《民法典》第577条 → 第584条 → 两个条号都真实存在、都在合同编,
                     内容对不对必须查库才知道
    """
    import legal_check as L
    cites = L.extract_citations(ans)
    if not cites:
        return None

    out, changed = ans, 0
    # 从后往前替换:先动靠后的引用,前面那些 citation 的位置偏移才不会失效
    for law, num, sub, end in sorted(cites, key=lambda c: -c[3]):
        arts = law_db.get(law)
        if not arts:
            continue
        src = arts.get((num, sub))
        if not src:
            continue                       # 原文引的条号本身就不在库里,跳过(别在错的基础上加错)

        # 在 ±max_shift 范围内找一个真实存在、且内容与原条文明显不同的条号
        cands = [n for n in range(max(1, num - max_shift), num + max_shift + 1)
                 if n != num and (n, 0) in arts
                 and L._char_overlap(arts[(n, 0)], src) < 0.15]     # 内容确实不一样
        if not cands:
            continue
        new = rng.choice(cands)

        # 定位这处引用的条号文字:它是 end 之前最后一个"第X条"
        m = None
        for m in re.finditer(rf"第\s*[{_CN}\d]+\s*条", out[:end]):
            pass
        if not m:
            continue

        # 【抽检修正】必须沿用原文的数字写法。原版一律写成中文,
        # 把"《公司法》第3条"改成了"第十四条" —— 数字格式的变化本身
        # 就成了新的表面特征,模型学"中文条号=坏的"就能全分对,等于白造。
        old = m.group()
        num_txt = str(new) if re.search(r"\d", old) else _int2cn(new)
        out = out[:m.start()] + f"第{num_txt}条" + out[m.end():]
        changed += 1

    return out if changed and _sane(out, ans) else None


def corrupt_term_swap(ans, rng=random, max_swap=3):
    """术语误用:换成"看着像但法律效果完全不同"的近义术语。

    这是最难被表面特征识破的一类 —— 替换前后都是标准法言法语,
    字数几乎不变,只有懂法的人才能看出结论错了。
    """
    hits = [(a, b) for a, b, _ in TERM_TRAPS if a in ans]
    if not hits:
        return None
    out = ans
    for a, b in rng.sample(hits, min(max_swap, len(hits))):
        out = out.replace(a, b)
    return out if _sane(out, ans) else None


def corrupt_degree(ans, rng=random, max_swap=2):
    """程度偏移:量刑档次/期限/比例改档。表述仍然专业,但适用结论错了。"""
    hits = [(a, b) for a, b in DEGREE_TRAPS if a in ans]
    if not hits:
        return None
    # 强特征(量刑/期限/比例)优先于通用词("可以→应当"),后者实测覆盖 72%,
    # 让它主导的话,它自己就变成了新的浅层判别特征。
    strong = [h for h in hits if h[0] not in _WEAK_DEGREE]
    hits = strong or hits
    out = ans
    # 长模式优先:先换"三年以下有期徒刑",再换"三年",否则短模式会抢先破坏长模式
    for a, b in sorted(rng.sample(hits, min(max_swap, len(hits))), key=lambda p: -len(p[0])):
        out = out.replace(a, b, 2)          # 最多换前 2 处,保留其余正确表述以增加迷惑性
    return out if _sane(out, ans) else None


def corrupt_subject(ans, rng=random, max_swap=2):
    """主体错置:权利义务主体对调。长度几乎不变、不含任何否定词。"""
    hits = []
    for pa, pb, a, b in SUBJECT_PAIRS:
        if re.search(pa, ans):
            hits.append((pa, b))            # A→B
        if re.search(pb, ans):
            hits.append((pb, a))            # B→A
    if not hits:
        return None
    out = ans
    for pat, repl in rng.sample(hits, min(max_swap, len(hits))):
        out = re.sub(pat, repl, out)        # 单向替换,不做双向交换(交换的改动点太多、反而显眼)
    return out if _sane(out, ans) else None


